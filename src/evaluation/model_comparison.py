"""Honest model comparison: rankings, hybrid-vs-baseline deltas, bootstrap CIs.

Nothing here favours the hybrid: the text is generated from the measured numbers
and says so explicitly when the hybrid is NOT the best on a metric.
"""
import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

from src import config

LOWER_IS_BETTER = {"Log Loss"}
KEY_METRICS = ["ROC-AUC", "PR-AUC", "F1", "MCC", "Recall", "Specificity", "Precision",
               "Accuracy", "Cohen's Kappa", "Log Loss"]


def rank_models(comparison: pd.DataFrame) -> pd.DataFrame:
    """Rank (1 = best) of every model on every metric."""
    ranks = pd.DataFrame({"Model": comparison["Model"]})
    for m in config.METRIC_COLUMNS:
        ranks[m] = comparison[m].rank(ascending=m in LOWER_IS_BETTER, method="min").astype(int)
    return ranks


def hybrid_vs_baselines(comparison: pd.DataFrame) -> pd.DataFrame:
    """Difference (hybrid - baseline) per metric.  Positive is better except for Log Loss."""
    hybrid = comparison[comparison["Model"] == config.HYBRID_NAME].iloc[0]
    rows = []
    for _, base in comparison[comparison["Model"] != config.HYBRID_NAME].iterrows():
        row = {"Baseline": base["Model"]}
        for m in config.METRIC_COLUMNS:
            row[m] = float(hybrid[m] - base[m])
        rows.append(row)
    return pd.DataFrame(rows)


def bootstrap_metric_difference(y_true, prob_a, prob_b, metric="roc_auc", n_boot=1000,
                                seed=config.RANDOM_STATE) -> dict:
    """Paired bootstrap of metric(A) - metric(B) on the test set (A = hybrid)."""
    y_true, prob_a, prob_b = map(np.asarray, (y_true, prob_a, prob_b))
    fn = roc_auc_score if metric == "roc_auc" else average_precision_score
    rng = np.random.default_rng(seed)
    n = len(y_true)
    diffs = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        if len(np.unique(y_true[idx])) < 2:
            continue
        diffs.append(fn(y_true[idx], prob_a[idx]) - fn(y_true[idx], prob_b[idx]))
    diffs = np.array(diffs)
    lo, hi = np.percentile(diffs, [2.5, 97.5])
    return {"observed_diff": float(fn(y_true, prob_a) - fn(y_true, prob_b)),
            "ci_low": float(lo), "ci_high": float(hi),
            "ci_contains_zero": bool(lo <= 0 <= hi), "n_boot": int(len(diffs))}


def bootstrap_table(predictions: pd.DataFrame, n_boot=1000) -> pd.DataFrame:
    rows = []
    for key in config.MODEL_NAMES:
        if key == config.HYBRID_KEY:
            continue
        for metric, label in (("roc_auc", "ROC-AUC"), ("pr_auc", "PR-AUC")):
            res = bootstrap_metric_difference(predictions["y_true"], predictions[f"prob_{config.HYBRID_KEY}"],
                                              predictions[f"prob_{key}"], metric, n_boot)
            rows.append({"Baseline": config.MODEL_NAMES[key], "Metric": label, **res})
    return pd.DataFrame(rows)


def _md_table(df: pd.DataFrame, digits=4) -> str:
    def fmt(v):
        return f"{v:.{digits}f}" if isinstance(v, (float, np.floating)) else str(v)
    lines = ["| " + " | ".join(map(str, df.columns)) + " |",
             "|" + "|".join(["---"] * len(df.columns)) + "|"]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def build_findings(comparison: pd.DataFrame, boot: pd.DataFrame) -> list[str]:
    """Plain-language findings generated from the actual numbers."""
    findings = []
    for m in KEY_METRICS:
        asc = m in LOWER_IS_BETTER
        best = comparison.sort_values(m, ascending=asc).iloc[0]
        h = comparison[comparison["Model"] == config.HYBRID_NAME].iloc[0]
        rank = int(comparison[m].rank(ascending=asc, method="min")[comparison["Model"] == config.HYBRID_NAME].iloc[0])
        if best["Model"] == config.HYBRID_NAME:
            findings.append(f"- **{m}**: the hybrid has the best value ({h[m]:.4f}).")
        else:
            findings.append(f"- **{m}**: best is {best['Model']} ({best[m]:.4f}); the hybrid "
                            f"({h[m]:.4f}) ranks {rank} of {len(comparison)}.")
    for _, r in boot.iterrows():
        verdict = ("the 95% bootstrap interval includes 0, so the difference is not statistically "
                   "distinguishable from noise on this test set" if r["ci_contains_zero"] else
                   "the 95% bootstrap interval excludes 0")
        findings.append(f"- Hybrid minus {r['Baseline']} in {r['Metric']}: {r['observed_diff']:+.4f} "
                        f"(95% CI {r['ci_low']:+.4f} to {r['ci_high']:+.4f}); {verdict}.")
    return findings


def write_results_summary(comparison, cv_summary, boot, path) -> None:
    """Write an auto-generated markdown summary of the real experiment results."""
    cv_cols = ["Model"] + [f"{m} {s}" for m in ("ROC-AUC", "PR-AUC", "F1", "MCC") for s in ("Mean", "Std")]
    text = ["# Results summary (auto-generated by run.py)", "",
            "All numbers below were computed from real predictions of the models trained by this run.", "",
            "## Test-set performance (20 % hold-out, threshold = "
            f"{config.DECISION_THRESHOLD})", "", _md_table(comparison), "",
            "## 5-fold stratified cross-validation (training data only)", "",
            _md_table(cv_summary[cv_cols]), "",
            "## Hybrid vs. each baseline on the test set", "", *build_findings(comparison, boot), "",
            "## Bootstrap comparison (paired, 1000 resamples of the test set)", "",
            _md_table(boot), "",
            "## Ranking (1 = best) per metric", "", _md_table(rank_models(comparison), digits=0), ""]
    path.write_text("\n".join(text), encoding="utf-8")
